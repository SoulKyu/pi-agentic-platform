import { randomUUID } from "node:crypto";
import {
  chmodSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { FONT_FAMILY_PATTERN, FONT_SLUG_PATTERN } from "@pap/contracts";
import { z } from "zod";
import { silentLogger, type Logger } from "../../kernel/logger.ts";

const WOFF2_NAME = /^[0-9a-f]{16}\.woff2$/;
const Meta = z.object({
  family: z.string().regex(FONT_FAMILY_PATTERN),
  addedAt: z.number().int(),
  files: z.array(z.string().regex(WOFF2_NAME)).max(64),
  bytes: z.number().int().min(0),
});

export interface StoredFamily {
  readonly slug: string;
  readonly family: string;
  readonly addedAt: number;
  readonly files: readonly string[];
  readonly bytes: number;
}

export interface ServedFile {
  readonly path: string;
  readonly size: number;
  readonly type: "font/woff2" | "text/css; charset=utf-8";
}

/**
 * `$PAP_HOME/fonts/<slug>/`: the woff2 files named by their content, `font.css` (generated by pap) and `meta.json`.
 * The folder is the record: there is no table. A family appears whole (renamed from a temp folder) or not at all.
 */
export function createFontsStore(root: string, logger: Logger = silentLogger) {
  const reported = new Set<string>(); // one line a slug, not one a request
  const readMeta = (slug: string): StoredFamily | null => {
    let raw: string;
    try {
      raw = readFileSync(join(root, slug, "meta.json"), "utf8");
    } catch {
      return null; // no record: not a family
    }
    try {
      return { slug, ...Meta.parse(JSON.parse(raw)) };
    } catch {
      if (!reported.has(slug)) {
        reported.add(slug);
        logger.warn("font_record_corrupt", { slug });
      }
      return null;
    }
  };
  const sweep = (names: readonly string[]): void => {
    for (const name of names) {
      if (!name.startsWith(".tmp-")) continue;
      try {
        rmSync(join(root, name), { recursive: true, force: true });
      } catch {
        logger.warn("font_sweep_failed", { name }); // best effort: the list goes on
      }
    }
  };
  return {
    list(): StoredFamily[] {
      let names: string[];
      try {
        names = readdirSync(root);
      } catch {
        return [];
      }
      sweep(names); // staging and trash folders a crash left behind (an install is synchronous: none is live)
      return names
        .filter((name) => FONT_SLUG_PATTERN.test(name))
        .map(readMeta)
        .filter((entry): entry is StoredFamily => entry !== null)
        .sort((one, other) => one.addedAt - other.addedAt || one.slug.localeCompare(other.slug));
    },
    get(slug: string): StoredFamily | null {
      return FONT_SLUG_PATTERN.test(slug) ? readMeta(slug) : null;
    },
    install(
      entry: Omit<StoredFamily, "files" | "bytes">,
      css: string,
      files: ReadonlyMap<string, Buffer>,
    ): StoredFamily {
      mkdirSync(root, { recursive: true, mode: 0o700 });
      chmodSync(root, 0o700);
      const staging = join(root, `.tmp-${randomUUID()}`);
      try {
        mkdirSync(staging, { mode: 0o700 });
        let bytes = 0;
        for (const [name, body] of files) {
          writeFileSync(join(staging, name), body, { mode: 0o600, flag: "wx" });
          bytes += body.length;
        }
        const names = [...files.keys()];
        writeFileSync(join(staging, "font.css"), css, { mode: 0o600, flag: "wx" });
        const meta = { family: entry.family, addedAt: entry.addedAt, files: names, bytes };
        writeFileSync(join(staging, "meta.json"), JSON.stringify(meta), { mode: 0o600, flag: "wx" });
        const target = join(root, entry.slug);
        // A folder without a valid record is a half install or a corrupt record: it makes room for this one.
        if (existsSync(target) && readMeta(entry.slug) === null)
          rmSync(target, { recursive: true, force: true });
        renameSync(staging, target);
        return { ...entry, files: names, bytes };
      } catch (error) {
        rmSync(staging, { recursive: true, force: true });
        throw error;
      }
    },
    remove(slug: string): boolean {
      if (!FONT_SLUG_PATTERN.test(slug) || readMeta(slug) === null) return false;
      const trash = join(root, `.tmp-trash-${randomUUID()}`);
      renameSync(join(root, slug), trash); // the family disappears at once; the delete can be finished later
      rmSync(trash, { recursive: true, force: true });
      return true;
    },
    /** A file the family recorded, as a regular file; anything else (a name, a slug, a symlink) is null. */
    read(slug: string, file: string): ServedFile | null {
      const meta = FONT_SLUG_PATTERN.test(slug) ? readMeta(slug) : null;
      if (meta === null || !(file === "font.css" || meta.files.includes(file))) return null;
      try {
        const path = join(root, slug, file);
        const stats = lstatSync(path);
        if (!stats.isFile()) return null;
        return {
          path,
          size: stats.size,
          type: file === "font.css" ? "text/css; charset=utf-8" : "font/woff2",
        };
      } catch {
        return null;
      }
    },
  };
}
export type FontsStore = ReturnType<typeof createFontsStore>;
